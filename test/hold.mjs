// Hold: a menu opened on hover stays open while the pointer goes anywhere, and closes again once let go
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const S = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'plugin', 'server') + '/';
const { launch, wait } = await import(S + 'chrome.mjs');
const { overlay } = await import(S + 'overlay.mjs');
const { THEME, ICONS } = await import(S + 'theme.mjs');
const { page, close } = await launch({ width: 1200, height: 800 });
let failures = 0;
const check = (ok, label, extra) => { console.log(`${ok ? 'PASS' : 'FAIL'}  ${label}${extra !== undefined ? `  ${JSON.stringify(extra)}` : ''}`); if (!ok) failures++; };
const html = `<body style="margin:0;font-family:Helvetica"><nav style="padding:20px;display:flex;gap:20px"><button id="t">Developers</button><button id="o">Pricing</button></nav><div id="m" hidden style="position:absolute;top:70px;left:20px;width:400px;height:200px;background:#fff;box-shadow:0 8px 30px rgba(0,0,0,.2)">Guides</div><script>const t = document.getElementById('t'), m = document.getElementById('m'); t.addEventListener('pointerenter', () => (m.hidden = false)); for (const e of [t, m]) e.addEventListener('pointerleave', (ev) => { if (!t.contains(ev.relatedTarget) && !m.contains(ev.relatedTarget)) m.hidden = true; });</script></body>`;
await page.send('Page.navigate', { url: 'data:text/html,' + encodeURIComponent(html) }); await wait(500);
await page.eval(`window.__spTheme = ${JSON.stringify(THEME)}; window.__spIcons = ${JSON.stringify(ICONS)}; window.__spProject = null; (${overlay})()`); await wait(300);
const at = (id) => page.eval(`(() => { const r = document.getElementById('${id}').getBoundingClientRect(); return { x: r.left + r.width / 2, y: r.top + r.height / 2 }; })()`);
const move = (x, y) => page.send('Input.dispatchMouseEvent', { type: 'mouseMoved', x, y });
const open = () => page.eval(`!document.getElementById('m').hidden`);
const t = await at('t'), o = await at('o');
await move(t.x, t.y); await wait(200);
check(await open(), 'the menu opens on hover');
await move(o.x, o.y); await wait(200); await move(900, 600); await wait(200);
check(!(await open()), 'without Hold it closes when the pointer leaves');
await move(t.x, t.y); await wait(200);
await page.send('Input.dispatchKeyEvent', { type: 'keyDown', key: 'h', code: 'KeyH', text: 'h' }); await page.send('Input.dispatchKeyEvent', { type: 'keyUp', key: 'h', code: 'KeyH' }); await wait(100);
check(await page.eval('window.__spTest.held()'), 'H holds the page');
await move(o.x, o.y); await wait(200); await move(900, 600); await wait(200);
check(await open(), 'held, it stays open wherever the pointer goes');
await page.eval('window.__spTest.hold(false)'); await move(t.x, t.y); await wait(100); await move(900, 600); await wait(200);
check(!(await open()), 'let go, the page hears the pointer again');
close();
console.log(failures ? `\n${failures} failed` : '\nall passed');
process.exit(failures ? 1 : 0);
